-- 2) إنشاء schema الـ Bronze
IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = 'BRONZE')
    EXEC('CREATE SCHEMA BRONZE');
GO

SELECT 'Orders'    AS tbl, COUNT(*) AS cnt FROM BRONZE.Orders
UNION ALL
SELECT 'Customers', COUNT(*) FROM BRONZE.Customers
UNION ALL
SELECT 'Products',  COUNT(*) FROM BRONZE.Products;

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'BRONZE'
ORDER BY TABLE_NAME, ORDINAL_POSITION;

SELECT TOP 10 Customer_Zipcode, COUNT(*) AS cnt
FROM BRONZE.Customers
GROUP BY Customer_Zipcode
ORDER BY cnt DESC;